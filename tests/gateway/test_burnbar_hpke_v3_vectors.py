def _import_relay_e2ee():
    try:
        from gateway.crypto import relay_e2ee  # type: ignore
    except Exception as exc:  # pragma: no cover - import guard
        pytest.skip(f"gateway.crypto.relay_e2ee not importable ({exc!r})")
    return relay_e2ee


def test_production_hpke_primitives_match_reference():
    """The Python lane's relay_e2ee HPKE primitives must be byte-identical to the
    reference, so a fixture generated by the reference opens under production."""
    prod = _import_relay_e2ee()
    for attr in (
        "_HPKE_KEM_SUITE_ID",
        "_HPKE_SUITE_ID",
        "_HPKE_INFO_PREFIX",
        "_hpke_extract_and_expand",
        "_hpke_auth_key_schedule",
        "_hpke_info",
    ):
        if not hasattr(prod, attr):
            pytest.skip(f"relay_e2ee has no {attr} yet (Python v3 lane in progress)")

    assert prod._HPKE_KEM_SUITE_ID == ref._KEM_SUITE_ID
    assert prod._HPKE_SUITE_ID == ref._HPKE_SUITE_ID
    assert prod._HPKE_INFO_PREFIX == ref.INFO_PREFIX

    # Use production primitives to open a real fixture wrap (assemble AuthDecap
    # around the production KDF/schedule/info). If it recovers the content key,
    # the production HPKE math matches the canonical vectors.
    case = CASES["phone_event_text"]
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    enc = _b64d(case["enc"])
    sk_r = ref.private_from_raw(_b64d(case["recipientPrivateKeyRaw"]))
    pk_s = ref.public_from_x963(_b64d(case["pinnedSenderPublicKeyX963"]))
    pk_e = ref.public_from_x963(enc)
    dh = sk_r.exchange(ec.ECDH(), pk_e) + sk_r.exchange(ec.ECDH(), pk_s)
    kem_context = enc + ref.serialize_public(sk_r.public_key()) + ref.serialize_public(pk_s)
    shared = prod._hpke_extract_and_expand(dh, kem_context)
    key, base_nonce = prod._hpke_auth_key_schedule(shared, prod._hpke_info(case["keyAAD"].encode()))
    content_key = AESGCM(key).decrypt(base_nonce, _b64d(case["wrappedKey"]), case["keyAAD"].encode())
    assert content_key == _b64d(case["plaintextContentKey"]), (
        "production relay_e2ee HPKE primitives do not open the canonical v3 vector"
    )


def test_production_public_v3_open_parity():
    """relay_e2ee.unwrap_symmetric_key_v3 must open every positive fixture wrap to
    the expected content key (full production-path parity — production opens the
    independent reference's vectors)."""
    prod = _import_relay_e2ee()
    if not hasattr(prod, "unwrap_symmetric_key_v3"):
        pytest.skip(
            "relay_e2ee.unwrap_symmetric_key_v3 not present yet; Python lane owns it. "
            "Primitive-level parity is already asserted by "
            "test_production_hpke_primitives_match_reference."
        )

    for case in POSITIVES:
        content_key = prod.unwrap_symmetric_key_v3(
            case["enc"],
            case["wrappedKey"],
            _b64d(case["recipientPrivateKeyRaw"]),
            case["keyAAD"].encode(),
            pinned_sender_public=case["pinnedSenderPublicKeyX963"],
        )
        assert content_key == _b64d(case["plaintextContentKey"]), (
            f"{case['name']}: production unwrap_symmetric_key_v3 returned a different content key"
        )


def test_production_and_reference_v3_are_bidirectionally_interoperable():
    """The strongest cross-stream proof: production opens the reference's wraps
    AND the reference opens production's wraps, for the same keys/aad/key."""
    prod = _import_relay_e2ee()
    if not (hasattr(prod, "wrap_symmetric_key_v3") and hasattr(prod, "unwrap_symmetric_key_v3")):
        pytest.skip("relay_e2ee public v3 wrap/unwrap not both present yet; Python lane owns it.")

    keys = FIXTURE["keys"]
    recipient_priv = _b64d(keys["agentRecipientPrivateKeyRaw"])
    recipient_pub = _b64d(keys["agentRecipientPublicKeyX963"])
    sender_priv = _b64d(keys["phoneSenderPrivateKeyRaw"])
    sender_pub = _b64d(keys["phoneSenderPublicKeyX963"])
    key_aad = CASES["phone_event_text"]["keyAAD"].encode()
    content_key = bytes(range(1, 33))

    # reference wraps -> production opens
    ref_enc, ref_wrapped = ref.wrap_content_key(content_key, recipient_pub, sender_priv, key_aad)
    assert (
        prod.unwrap_symmetric_key_v3(
            ref_enc, ref_wrapped, recipient_priv, key_aad, pinned_sender_public=keys["phoneSenderPublicKeyX963"]
        )
        == content_key
    ), "production failed to open a reference-generated v3 wrap"

    # production wraps -> reference opens
    prod_wrap = prod.wrap_symmetric_key_v3(
        content_key, keys["agentRecipientPublicKeyX963"], key_aad, sender_private=sender_priv
    )
    assert (
        ref.open_content_key(prod_wrap.enc, prod_wrap.wrapped_key, recipient_priv, sender_pub, key_aad)
        == content_key
    ), "reference failed to open a production-generated v3 wrap"

    # the pinned-sender binding holds across implementations: a wrong pin fails.
    with pytest.raises(InvalidTag):
        prod.unwrap_symmetric_key_v3(
            ref_enc,
            ref_wrapped,
            recipient_priv,
            key_aad,
            pinned_sender_public=keys["agentRecipientPublicKeyX963"],  # wrong pin
        )


def test_downgrade_and_strip_fail_closed_in_production():
    """Prove the SHIPPED fail-closed behavior when a relay downgrades or strips a
    sealed v3 frame, against the REAL relay_e2ee openers (the adapter dispatches
    the supported {v2, v3} set by version; this exercises the openers it routes
    to). The security property: no older opener can extract the content key from
    the v3 bytes, and the v3 opener requires the exact HPKE marker."""
    prod = _import_relay_e2ee()
    for attr in (
        "unwrap_symmetric_key",
        "unwrap_symmetric_key_v3",
        "InvalidCiphertextError",
        "HPKE_ALGORITHM",
    ):
        if not hasattr(prod, attr):
            pytest.skip(f"relay_e2ee.{attr} not present yet; Python lane owns it.")

    base = CASES["phone_event_text"]
    recipient_priv = _b64d(base["recipientPrivateKeyRaw"])
    pinned = base["pinnedSenderPublicKeyX963"]
    key_aad = base["keyAAD"].encode()

    # Positive control: the v3 opener with correct params DOES recover the key.
    assert (
        prod.unwrap_symmetric_key_v3(
            base["enc"], base["wrappedKey"], recipient_priv, key_aad, pinned_sender_public=pinned
        )
        == _b64d(base["plaintextContentKey"])
    )

    # v3 -> v2 downgrade: production routes a relayKeyVersion=2 frame to the v2
    # opener, which fails closed because the 48-byte v3 wrappedKey is shorter than
    # the v2 minimum (enc(65) ‖ nonce(12) ‖ ct ‖ tag(16)). Key never recovered.
    assert len(_b64d(base["wrappedKey"])) == 48
    with pytest.raises(prod.InvalidCiphertextError):
        prod.unwrap_symmetric_key(
            base["wrappedKey"], recipient_priv, key_aad, sender_public_base64=pinned
        )

    # Even the v1 anonymous opener (no sender pin) fails closed on the v3 bytes,
    # so a v1 relabel can extract nothing either.
    with pytest.raises(prod.InvalidCiphertextError):
        prod.unwrap_symmetric_key(base["wrappedKey"], recipient_priv, key_aad)

    # Stripped/incorrect HPKE marker: the v3 dispatch requires the exact marker
    # (the adapter refuses a v3 frame whose relayEncryption != HPKE_ALGORITHM).
    assert base["relayEncryption"] == prod.HPKE_ALGORITHM
