"""Canonical cross-language verifier for the BurnBar HPKE **v3** relay wrap.

This is the vector lane's stop-condition suite. It loads the canonical fixture
``tests/gateway/fixtures/BurnBarHpkeV3Vector.json`` (regenerate with
``python -m tests.gateway.vectors.generate_burnbar_hpke_v3_vectors``) and proves:

* every positive case's HPKE wrap opens to the expected content key under the
  PINNED sender key, and the sealed payload opens to the expected plaintext;
* inbound event / model_switch payloads carry the strict ``destinationId`` +
  ``replayCounter``/``eventCounter`` schema the production adapter enforces;
* every negative mutation (forgery, tamper, downgrade, stripped marker) is
  rejected fail-closed;
* the fixture metadata is the frozen v3 contract and every authenticated field
  is inspectable;
* the production ``gateway/crypto/relay_e2ee.py`` HPKE primitives are
  byte-identical to the reference, and — once the Python lane lands a public v3
  open — that it opens these exact vectors (auto-detected; skips with an
  actionable reason until then).

The fixture is generated by an independent RFC 9180 reference
(``tests/gateway/vectors/hpke_v3_reference.py``); Swift CryptoKit opens the same
fixture in ``BurnBarHpkeV3CrossPlatformVectorTests.swift`` — three independent
implementations agreeing is the cross-language proof.
"""

from __future__ import annotations

import base64
import json
from pathlib import Path

import pytest
from cryptography.exceptions import InvalidTag

from tests.gateway.vectors import hpke_v3_reference as ref

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "BurnBarHpkeV3Vector.json"

REQUIRED_POSITIVES = {
    "phone_event_text",
    "phone_event_model_switch",
    "agent_reply_text",
    "agent_reply_attachment_manifest",
    "agent_reply_attachment_body_key",
}
REQUIRED_NEGATIVES = {
    "wrong_pinned_sender_key",
    "wrong_recipient_key",
    "wrong_key_aad",
    "mutated_enc",
    "mutated_wrapped_key",
    "version_changed_to_2",
    "version_changed_to_1",
    "missing_enc",
    "missing_relay_encryption",
}
# Event-shaped kinds whose opened payload must satisfy the strict inbound schema.
_EVENT_KINDS = {"event", "model_switch"}
_JSON_DESTINATION_KINDS = {"event", "model_switch", "message", "attachment_manifest"}
_REPLAY_KEYS = ("replayCounter", "eventCounter")


def _load() -> dict:
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


FIXTURE = _load()
CASES = {c["name"]: c for c in FIXTURE["cases"]}
POSITIVES = [c for c in FIXTURE["cases"] if c["expected"] == "open"]
NEGATIVES = [c for c in FIXTURE["cases"] if c["expected"] == "reject"]


def _b64d(value: str) -> bytes:
    return base64.b64decode(value, validate=True)


