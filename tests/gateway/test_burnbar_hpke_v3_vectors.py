def test_fixture_is_the_frozen_v3_contract():
    assert FIXTURE["schemaVersion"] == 1
    assert FIXTURE["relayKeyVersion"] == 3
    assert FIXTURE["relayEncryption"] == "hpke-auth-p256-hkdfsha256-aes256gcm"
    suite = FIXTURE["suite"]
    assert suite["mode"] == "auth"
    assert (suite["kemId"], suite["kdfId"], suite["aeadId"], suite["modeId"]) == (
        0x0010,
        0x0001,
        0x0002,
        0x02,
    )
    assert FIXTURE["hpke"]["infoPrefix"] == "OpenBurnBar-HermesRelay-HPKE-v3|"
    # A reviewer must be able to regenerate it and find every authenticated field.
    assert FIXTURE["generator"]["command"]
    keys = FIXTURE["keys"]
    for required in (
        "agentRecipientPublicKeyX963",
        "agentRecipientPrivateKeyRaw",
        "phoneSenderPublicKeyX963",
        "phoneSenderPrivateKeyRaw",
    ):
        assert keys.get(required), f"missing fixture key material: {required}"


def test_fixture_has_every_required_case():
    assert REQUIRED_POSITIVES <= {c["name"] for c in POSITIVES}
    assert REQUIRED_NEGATIVES <= {c["name"] for c in NEGATIVES}


def test_every_authenticated_field_is_identifiable():
    """Vector-agent stop condition: a reviewer can inspect the JSON and identify
    every authenticated field (the HPKE info, key_aad, enc, wrappedKey, and the
    payload AAD that binds the sealed plaintext)."""
    for case in POSITIVES:
        for field in ("keyAAD", "info", "enc", "wrappedKey", "payloadAAD", "plaintextContentKey"):
            assert case.get(field), f"{case['name']} is missing inspectable field {field}"
        # info is exactly the prefixed key_aad — the binding is visible, not opaque.
        assert case["info"] == "OpenBurnBar-HermesRelay-HPKE-v3|" + case["keyAAD"]


# ---------------------------------------------------------------------------
# Positive cases: open the content key + the sealed payload, check strict schema
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("case", POSITIVES, ids=[c["name"] for c in POSITIVES])
def test_positive_case_opens_with_pinned_sender(case):
    enc, wrapped = ref.parse_strict_v3_envelope(_envelope_for(case))

    content_key = ref.open_content_key(
        enc,
        wrapped,
        _b64d(case["recipientPrivateKeyRaw"]),
        _b64d(case["pinnedSenderPublicKeyX963"]),
        case["keyAAD"].encode(),
    )
    assert content_key == _b64d(case["plaintextContentKey"]), "unwrapped content key mismatch"

    payload = ref.open_payload_base64(
        case["payloadCiphertext"], content_key, case["payloadAAD"].encode()
    )
    assert payload.decode("utf-8") == case["payloadPlaintext"], "sealed payload mismatch"

    if case["kind"] in _EVENT_KINDS:
        _assert_strict_event_schema(case, payload)
    if case["kind"] in _JSON_DESTINATION_KINDS:
        _assert_destination_bound(case, payload)


def _assert_strict_event_schema(case, payload: bytes):
    """Mirror plugins/platforms/burnbar/adapter.py: a sealed inbound event the
    agent accepts MUST carry an authenticated destinationId and a non-negative
    replayCounter/eventCounter."""
    obj = json.loads(payload.decode("utf-8"))
    assert isinstance(obj.get("destinationId"), str) and obj["destinationId"], (
        f"{case['name']}: sealed event missing authenticated destinationId"
    )
    counters = [obj[k] for k in _REPLAY_KEYS if k in obj]
    assert counters, f"{case['name']}: sealed event missing replayCounter/eventCounter"
    assert all(isinstance(c, int) and c >= 0 for c in counters), (
        f"{case['name']}: replay counter must be a non-negative integer"
    )


def _assert_destination_bound(case, payload: bytes):
    obj = json.loads(payload.decode("utf-8"))
    assert obj.get("destinationId") == "burnbar:home", (
        f"{case['name']}: sealed JSON payload missing authenticated destinationId"
    )


# ---------------------------------------------------------------------------
# Negative cases: every mutation is rejected fail-closed
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("neg", NEGATIVES, ids=[c["name"] for c in NEGATIVES])
def test_negative_case_is_rejected(neg):
    base = CASES[neg["derivedFrom"]]
    envelope = _envelope_for(base)

    # Apply the structural mutations (downgrade / stripped marker / mutated bytes).
    if "relayKeyVersionOverride" in neg:
        envelope["relayKeyVersion"] = neg["relayKeyVersionOverride"]
    if neg.get("dropField"):
        envelope.pop(neg["dropField"], None)
    if "encOverride" in neg:
        envelope["enc"] = neg["encOverride"]
    if "wrappedKeyOverride" in neg:
        envelope["wrappedKey"] = neg["wrappedKeyOverride"]

    key_aad = neg.get("keyAADOverride", base["keyAAD"]).encode()
    recipient_priv = _b64d(neg.get("recipientPrivateKeyRawOverride", base["recipientPrivateKeyRaw"]))
    pinned_sender = _b64d(
        neg.get("pinnedSenderPublicKeyX963Override", base["pinnedSenderPublicKeyX963"])
    )

    # Tight per-negative expectation: assert the EXACT failure class the mutation
    # should produce. A broad tuple (incl. ValueError) would let a base64-decode
    # artifact (binascii.Error subclasses ValueError) masquerade as a real reject.
    expected_error = _EXPECTED_ERROR[neg["expectedError"]]
    with pytest.raises(expected_error):
        enc, wrapped = ref.parse_strict_v3_envelope(envelope)
        ref.open_content_key(enc, wrapped, recipient_priv, pinned_sender, key_aad)


_EXPECTED_ERROR = {
    "InvalidTag": InvalidTag,
    "HpkeError": ref.HpkeError,
    "RelayV3EnvelopeError": ref.RelayV3EnvelopeError,
}


def test_negative_cases_are_only_rejected_by_their_mutation():
    """Guard against a vacuous negative: the un-mutated base of every negative
    MUST open, so each rejection is caused by the mutation, not a broken base."""
    for neg in NEGATIVES:
        base = CASES[neg["derivedFrom"]]
        enc, wrapped = ref.parse_strict_v3_envelope(_envelope_for(base))
        content_key = ref.open_content_key(
            enc,
            wrapped,
            _b64d(base["recipientPrivateKeyRaw"]),
            _b64d(base["pinnedSenderPublicKeyX963"]),
            base["keyAAD"].encode(),
        )
        assert content_key == _b64d(base["plaintextContentKey"])


def _envelope_for(case: dict) -> dict:
    """The relay-visible sealed envelope fields for a case (a fresh dict each
    call so mutations never leak across cases)."""
    return {
        "relayKeyVersion": case["relayKeyVersion"],
        "relayEncryption": case["relayEncryption"],
        "enc": case["enc"],
        "wrappedKey": case["wrappedKey"],
        "senderPublicKey": case["senderPublicKeyX963"],
    }


